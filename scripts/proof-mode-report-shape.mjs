#!/usr/bin/env node

/**
 * Derive what the gate report generates, from the report it actually ships.
 *
 * This page used to be able to describe a payload nobody had checked against
 * the runner. That is not hypothetical: the runner's own delivery checks were
 * written against an imagined shape and spent their life reporting `skipped`
 * on a report full of what they were looking for. A docs page repeating the
 * same guess would be the third copy of it.
 *
 * So the block list comes out of `proof-mode-gates/templates/report.html` — the
 * canonical payload — and the prose lives here keyed by block. `--check`
 * re-derives and fails when the two no longer line up, which is what stops a
 * new block from shipping undocumented, or a documented one from outliving the
 * report.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import process from 'node:process'

const ROOT = resolve(import.meta.dirname, '..')
const TEMPLATE = resolve(ROOT, '../proof-mode-gates/templates/report.html')
const CLI = resolve(ROOT, '../proof-mode-gates/src/cli.ts')
const TARGET = resolve(ROOT, 'src/data/proof-mode-report.ts')

const PAYLOAD =
	/<script type="application\/json" id="gate-report">([\s\S]*?)<\/script>/

/** What each block is there to stop — authored, not derived. */
const STOPS = {
	backend: 'a spec nobody tested, and a migration nobody described',
	changed: 'green whose scope nobody checked',
	context: 'work built over a missing input (DLV-1)',
	contractDelta: 'a breaking change discovered by a consumer (DLV-15)',
	frontend: 'a happy-path screenshot standing in for five states',
	ladder: '"it works on my machine"',
	law: 'a `manual` binding read as automatically satisfied',
	provenance:
		'green under one version of a skill read as evidence under another',
	raw: 'a green summary the tools never actually printed',
	schema: 'a renderer computing a verdict from a payload it cannot read',
	task: 'a report describing a different commit than the one under review',
}

function payloadOf() {
	const match = PAYLOAD.exec(readFileSync(TEMPLATE, 'utf8'))

	if (!match) {
		throw new Error('the shipped template has no #gate-report payload')
	}

	return JSON.parse(match[1])
}

/** A one-line shape, the way a reader would sketch it. */
function sketch(value) {
	if (Array.isArray(value)) {
		return value.length > 0 ? `[${sketch(value[0])}]` : '[]'
	}

	if (value && typeof value === 'object') {
		return `{ ${Object.keys(value).join(', ')} }`
	}

	return typeof value
}

/** The commands, read from the CLI's own help rather than restated. */
function commands() {
	const help = readFileSync(CLI, 'utf8')
	const block = /const HELP = `([\s\S]*?)`/.exec(help)

	if (!block) {
		throw new Error('cannot find the CLI help text')
	}

	return [
		...block[1].matchAll(/^ {2}(turystack-proof [^\n]+?) {2,}(.+)$/gm),
	].map((match) => ({
		command: match[1].trim(),
		does: match[2].trim(),
	}))
}

function generate() {
	const payload = payloadOf()
	const blocks = Object.entries(payload).map(([name, value]) => {
		const stops = STOPS[name]

		if (!stops) {
			throw new Error(
				`the report ships a '${name}' block with no note in STOPS — say what it is there to stop`,
			)
		}

		return {
			name,
			shape: sketch(value),
			stops,
		}
	})

	const known = Object.keys(STOPS).filter((name) => !(name in payload))

	if (known.length > 0) {
		throw new Error(
			`STOPS describes ${known.join(', ')}, which the shipped report no longer carries`,
		)
	}

	return `/**
 * Generated by scripts/proof-mode-report-shape.mjs — do not edit.
 *
 * Derived from @turystack/proof-mode-gates' own templates/report.html and its
 * CLI help, so this page cannot describe a report the runner does not emit.
 * Run \`pnpm report-shape:write\` after changing either.
 */

export type ReportBlock = {
	name: string
	shape: string
	stops: string
}

export type ReportCommand = {
	command: string
	does: string
}

export const reportBlocks: ReportBlock[] = ${JSON.stringify(blocks, null, '\t')}

export const reportCommands: ReportCommand[] = ${JSON.stringify(commands(), null, '\t')}
`
}

/**
 * A new block with no note is a gate failure, not a stack trace.
 *
 * The runner gaining a block is the normal case this exists to catch — it has
 * to read as "say what this is for", not as a crashed script.
 */
let generated

try {
	generated = generate()
} catch (error) {
	process.stdout.write(`\n✖ proof-mode report shape: ${error.message}\n\n`)
	process.exitCode = 1
	process.exit(1)
}

if (process.argv.includes('--check')) {
	const current = (() => {
		try {
			return readFileSync(TARGET, 'utf8')
		} catch {
			return ''
		}
	})()

	if (current === generated) {
		const blocks = (generated.match(/"name":/g) ?? []).length
		process.stdout.write(
			`\n✓ proof-mode report: ${blocks} block(s) match the shipped template and CLI\n\n`,
		)
	} else {
		process.stdout.write(
			'\n✖ src/data/proof-mode-report.ts no longer matches what @turystack/proof-mode-gates emits — run `pnpm report-shape:write`\n' +
				'  This page would describe a report the runner does not generate.\n\n',
		)
		process.exitCode = 1
	}
} else {
	writeFileSync(TARGET, generated, 'utf8')
	const blocks = (generated.match(/"name":/g) ?? []).length
	process.stdout.write(
		`✓ wrote src/data/proof-mode-report.ts — ${blocks} block(s)\n`,
	)
}
